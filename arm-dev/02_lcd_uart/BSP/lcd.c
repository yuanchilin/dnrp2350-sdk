{
    LCD_CS_LOW();
    LCD_DC_DATA();
    spi_write_blocking(LCD_SPI_PORT, &data, 1);
    LCD_CS_HIGH();
}

static void lcd_write_data16(uint16_t data)
{
    uint8_t buf[2] = { (uint8_t)(data >> 8), (uint8_t)(data & 0xFF) };
    LCD_CS_LOW();
    LCD_DC_DATA();
    spi_write_blocking(LCD_SPI_PORT, buf, 2);
    LCD_CS_HIGH();
}

/* ========================================================================== */
/*  内部函数：ST7789 寄存器操作                                                */
/* ========================================================================== */
static void lcd_set_window(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2)
{
    lcd_write_cmd(0x2A);                /* 列地址设置 */
    lcd_write_data16(x1);
    lcd_write_data16(x2);

    lcd_write_cmd(0x2B);                /* 行地址设置 */
    lcd_write_data16(y1);
    lcd_write_data16(y2);

    lcd_write_cmd(0x2C);                /* 内存写 */
}

/* ========================================================================== */
/*  初始化 ST7789                                                              */
/* ========================================================================== */
void lcd_init(void)
{
    /* ---- GPIO 初始化 ---- */
    spi_init(LCD_SPI_PORT, 50 * 1000 * 1000);  /* SPI1 @ 50MHz */
    gpio_set_function(LCD_SCK_PIN,  GPIO_FUNC_SPI);
    gpio_set_function(LCD_MOSI_PIN, GPIO_FUNC_SPI);

    gpio_init(LCD_CS_PIN);
    gpio_set_dir(LCD_CS_PIN, GPIO_OUT);
    gpio_put(LCD_CS_PIN, 1);

    gpio_init(LCD_DC_PIN);
    gpio_set_dir(LCD_DC_PIN, GPIO_OUT);
    gpio_put(LCD_DC_PIN, 1);

    /* ---- 背光 PWM ---- */
    gpio_set_function(LCD_BL_PIN, GPIO_FUNC_PWM);
    uint slice = pwm_gpio_to_slice_num(LCD_BL_PIN);
    pwm_set_wrap(slice, 100);
    pwm_set_chan_level(slice, PWM_CHAN_B, 100);
    pwm_set_enabled(slice, true);

    /* ---- 硬件复位（软件命令） ---- */
    sleep_ms(10);
    lcd_write_cmd(0x01);                /* 软件复位 */
    sleep_ms(150);

    /* ---- ST7789 初始化序列 ---- */
    lcd_write_cmd(0x11);                /* 退出睡眠 */
    sleep_ms(120);

    lcd_write_cmd(0x36);                /* MADCTL: 内存数据访问控制 */
    lcd_write_data(0x00);               /* 竖屏，不翻转 */

    lcd_write_cmd(0x3A);                /* COLMOD: 像素格式 */
    lcd_write_data(0x05);               /* 16-bit RGB565 */

    lcd_write_cmd(0xB2);                /* PORCTRL: 门控时序 */
    lcd_write_data(0x0C);
    lcd_write_data(0x0C);
    lcd_write_data(0x00);
    lcd_write_data(0x33);
    lcd_write_data(0x33);

    lcd_write_cmd(0xB7);                /* GCTRL: 门控电压 */
    lcd_write_data(0x35);

    lcd_write_cmd(0xBB);                /* VCOMS: VCOM 偏移 */
    lcd_write_data(0x19);

    lcd_write_cmd(0xC0);                /* LCMCTRL: LCM 控制 */
    lcd_write_data(0x2C);

    lcd_write_cmd(0xC2);                /* VDVVRHEN: VDV/VRH 使能 */
    lcd_write_data(0x01);

    lcd_write_cmd(0xC3);                /* VRHS: VRH 设置 */
    lcd_write_data(0x12);

    lcd_write_cmd(0xC4);                /* VDVS: VDV 设置 */
    lcd_write_data(0x20);

    lcd_write_cmd(0xC6);                /* FRCTRL2: 帧率控制 */
    lcd_write_data(0x0F);

    lcd_write_cmd(0xD0);                /* PWCTRL1: 电源控制 1 */
    lcd_write_data(0xA4);
    lcd_write_data(0xA1);

    lcd_write_cmd(0xE0);                /* PVGAMCTRL: 正极性 Gamma */
    lcd_write_data(0xD0);
    lcd_write_data(0x04);
    lcd_write_data(0x0D);
    lcd_write_data(0x11);
    lcd_write_data(0x13);
    lcd_write_data(0x2B);
    lcd_write_data(0x3F);
    lcd_write_data(0x54);
    lcd_write_data(0x4C);
    lcd_write_data(0x18);
    lcd_write_data(0x0D);
    lcd_write_data(0x0B);
    lcd_write_data(0x1F);
    lcd_write_data(0x23);

    lcd_write_cmd(0xE1);                /* NVGAMCTRL: 负极性 Gamma */
    lcd_write_data(0xD0);
    lcd_write_data(0x04);
    lcd_write_data(0x0C);
    lcd_write_data(0x11);
    lcd_write_data(0x13);
    lcd_write_data(0x2C);
    lcd_write_data(0x3F);
    lcd_write_data(0x44);
    lcd_write_data(0x51);
    lcd_write_data(0x2F);
    lcd_write_data(0x1F);
    lcd_write_data(0x1F);
    lcd_write_data(0x20);
    lcd_write_data(0x23);

    lcd_write_cmd(0x29);                /* 显示开启 */
    sleep_ms(50);
}

/* ========================================================================== */
/*  背光控制 (0~100)                                                           */
/* ========================================================================== */
void lcd_set_backlight(uint8_t brightness)
{
    if (brightness > 100) brightness = 100;
    uint slice = pwm_gpio_to_slice_num(LCD_BL_PIN);
    pwm_set_chan_level(slice, PWM_CHAN_B, brightness);
}

/* ========================================================================== */
/*  清屏                                                                       */
/* ========================================================================== */
void lcd_clear(uint16_t color)
{
    lcd_fill(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1, color);
}

/* ========================================================================== */
/*  矩形填充                                                                   */
/* ========================================================================== */
void lcd_fill(uint16_t x1, uint16_t y1, uint16_t x2, uint16_t y2, uint16_t color)
{
    if (x1 > LCD_WIDTH || y1 > LCD_HEIGHT || x2 > LCD_WIDTH || y2 > LCD_HEIGHT)
        return;

    uint32_t n = (uint32_t)(x2 - x1 + 1) * (y2 - y1 + 1);
    uint8_t hi = (uint8_t)(color >> 8);
    uint8_t lo = (uint8_t)(color & 0xFF);

    lcd_set_window(x1, y1, x2, y2);

    LCD_CS_LOW();
    LCD_DC_DATA();

    /* 批量传输优化: 64 像素一组 */
    for (uint32_t i = 0; i < n; i++) {
        uint8_t buf[2] = { hi, lo };
        spi_write_blocking(LCD_SPI_PORT, buf, 2);
    }

    LCD_CS_HIGH();
}

/* ========================================================================== */
/*  画点                                                                       */
/* ========================================================================== */
void lcd_draw_pixel(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;

    lcd_set_window(x, y, x, y);
    lcd_write_data16(color);
}

/* ========================================================================== */
/*  显示字符 (8x16)                                                            */
/* ========================================================================== */
void lcd_show_char(uint16_t x, uint16_t y, char ch, uint16_t color, uint16_t bg)
{
    if (x + 8 > LCD_WIDTH || y + 16 > LCD_HEIGHT) return;
    if (ch < 0x20 || ch > 0x7E) ch = ' ';       /* 非打印字符替换为空格 */

    const uint8_t *bitmap = font_8x16[ch - 0x20];

    lcd_set_window(x, y, x + 7, y + 15);
    LCD_CS_LOW();
    LCD_DC_DATA();

    for (int row = 0; row < 16; row++) {
        uint8_t line = bitmap[row];
        for (int col = 0; col < 8; col++) {
            uint16_t c = (line & (0x80 >> col)) ? color : bg;
            uint8_t buf[2] = { (uint8_t)(c >> 8), (uint8_t)(c & 0xFF) };
            spi_write_blocking(LCD_SPI_PORT, buf, 2);
        }
    }

    LCD_CS_HIGH();
}

/* ========================================================================== */
/*  显示字符串                                                                 */
/* ========================================================================== */
void lcd_show_string(uint16_t x, uint16_t y, const char *str, uint16_t color, uint16_t bg)
{
    while (*str) {
        if (*str == '\n') {
            y += 16;
            x = 0;                              /* 简易换行：回到行首 */
        } else {
            lcd_show_char(x, y, *str, color, bg);
            x += 8;
            if (x + 8 > LCD_WIDTH) {
                x = 0;
                y += 16;
            }
        }
        if (y + 16 > LCD_HEIGHT) break;
        str++;
    }
}

/* ========================================================================== */
/*  显示数字                                                                   */
/* ========================================================================== */
void lcd_show_num(uint16_t x, uint16_t y, int num, uint8_t len, uint16_t color, uint16_t bg)
{
    char buf[12];
    snprintf(buf, sizeof(buf), "%*d", len, num);
    lcd_show_string(x, y, buf, color, bg);
}
